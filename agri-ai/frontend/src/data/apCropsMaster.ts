/**
 * Alphabetically sorted master array of all AP crops
 */
export const AP_CROPS_MASTER: APCropMasterItem[] = [...RAW_CROP_DEFINITIONS].sort((a, b) =>
  a.name.localeCompare(b.name)
).map((item) => ({
  name: item.name,
  queryKey: item.queryKey,
  group: item.group,
  emoji: item.emoji || '🌿',
}))

export const getMasterCropByQuery = (cropVal: string): APCropMasterItem | undefined => {
  if (!cropVal || cropVal === 'all') return undefined
  return AP_CROPS_MASTER.find(
    (c) =>
      c.name.toLowerCase() === cropVal.toLowerCase() ||
      c.queryKey.toLowerCase() === cropVal.toLowerCase()
  )
}
